'use strict';
// Server-generated names only. Uploaded snapshots are validated before being listed or restored.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { route, fail } = require('../http');
const config = require('../config');
const store = require('../store');
const sec = require('../security');
const autoBackup = require('../auto-backup');
const ADMIN = { roles: ['admin'] };
const dir = () => path.join(config.DATA_DIR, 'backups');
const UPLOAD_LIMIT = 512 * 1024 * 1024;
const namePattern = /^baboltoyor-(?:manual|before-restore|uploaded|auto)-\d{8}T\d{6}-[a-f0-9]{12}\.db$/;
function safeFile(name) {
  if (!namePattern.test(String(name))) fail(400, 'نام پشتیبان معتبر نیست.');
  const base = name.startsWith('baboltoyor-auto-') ? autoBackup.read().directory : dir();
  if (!base || !path.isAbsolute(base)) fail(404, 'پوشهٔ پشتیبان خودکار تنظیم نشده است.');
  const file = path.join(base, name);
  let st; try { st = fs.lstatSync(file); } catch { fail(404, 'پشتیبان پیدا نشد.'); }
  if (!st.isFile() || st.isSymbolicLink()) fail(400, 'فایل پشتیبان معتبر نیست.');
  return file;
}
function makeName(kind) {
  const stamp = new Date().toISOString().replace(/[-:]/g, '').slice(0, 15);
  return `baboltoyor-${kind}-${stamp}-${crypto.randomBytes(6).toString('hex')}.db`;
}
function create(kind) {
  fs.mkdirSync(dir(), { recursive: true, mode: 0o700 });
  const name = makeName(kind);
  const file = path.join(dir(), name);
  try { store.sql.vacuumInto(file); } catch (e) { try { fs.unlinkSync(file); } catch {} throw e; }
  try { fs.chmodSync(file, 0o600); } catch { /* Windows uses directory ACLs */ }
  return name;
}
route('GET', '/api/admin/backups', ADMIN, async () => {
  fs.mkdirSync(dir(), { recursive: true, mode: 0o700 });
  const schedule = autoBackup.read();
  const locations = [{directory:dir(), auto:false}];
  if (schedule.directory && path.isAbsolute(schedule.directory)) locations.push({directory:schedule.directory,auto:true});
  const backups = locations.flatMap(({directory,auto}) => {
    try { return fs.readdirSync(directory).filter(n => namePattern.test(n) && n.startsWith('baboltoyor-auto-')===auto).flatMap(name => {
      try { const st=fs.lstatSync(path.join(directory,name)); return st.isFile()&&!st.isSymbolicLink()?[{name,size:st.size,createdAt:st.mtime.toISOString(),automatic:auto}]:[]; } catch { return []; }
    }); } catch { return []; }
  }).sort((a,b) => b.createdAt.localeCompare(a.createdAt));
  let autoCount=0; const visible=backups.filter(b => !b.automatic || ++autoCount<=200);
  return { body: { backups: visible, schedule, automaticCount: autoCount } };
});
route('PUT', '/api/admin/backups/schedule', ADMIN, async ctx => {
  let schedule;
  try { schedule=autoBackup.configure(ctx.body); } catch(e) { fail(400, `ذخیرهٔ تنظیمات انجام نشد: ${e.message}`); }
  store.audit(ctx.user,'AUTO_BACKUP_SETTINGS','backup','schedule',{enabled:schedule.enabled,directory:schedule.directory},ctx); store.save();
  return {body:{schedule}};
});
route('POST', '/api/admin/backups', ADMIN, async ctx => {
  const name = create('manual');
  store.audit(ctx.user, 'BACKUP_CREATED', 'backup', name, {}, ctx); store.save();
  return { status: 201, body: { name } };
});
// The request is a raw file, not multipart/form-data: the non-simple content type and
// custom header prevent cross-site HTML forms from making an authenticated upload.
route('POST', '/api/admin/backups/upload', { ...ADMIN, streamBody: true }, async ctx => {
  const req = ctx.req;
  if (String(req.headers['content-type'] || '').toLowerCase().split(';')[0].trim() !== 'application/octet-stream' || req.headers['x-backup-upload'] !== '1') {
    req.resume(); fail(415, 'نوع درخواست بارگذاری معتبر نیست.');
  }
  const length = Number(req.headers['content-length'] || 0);
  if (!Number.isSafeInteger(length) || length < 0 || length > UPLOAD_LIMIT) { req.resume(); fail(413, 'حجم فایل بیش از ۵۱۲ مگابایت است.'); }
  fs.mkdirSync(dir(), { recursive: true, mode: 0o700 });
  const name = makeName('uploaded');
  const temp = path.join(dir(), `.upload-${crypto.randomBytes(16).toString('hex')}.tmp`);
  const final = path.join(dir(), name);
  let handle, linked = false, completed = false;
  try {
    handle = await fs.promises.open(temp, 'wx', 0o600);
    let size = 0;
    for await (const chunk of req) {
      size += chunk.length;
      if (size > UPLOAD_LIMIT) fail(413, 'حجم فایل بیش از ۵۱۲ مگابایت است.');
      await handle.writeFile(chunk);
    }
    await handle.close(); handle = null;
    if (!sec.getSession(ctx.sid)) fail(401, 'نشست پایان یافته است؛ دوباره وارد شوید.', 'AUTH_REQUIRED');
    if (size < 100) fail(400, 'فایل پشتیبان خالی یا نامعتبر است.');
    try { store.sql.validateSnapshot(temp); }
    catch { fail(400, 'فایل پشتیبان سالم یا با ساختار این سامانه سازگار نیست.'); }
    // Link is atomic and never overwrites another file. Names are generated by the server.
    await fs.promises.link(temp, final); linked = true;
    if (!sec.getSession(ctx.sid)) fail(401, 'نشست پایان یافته است؛ دوباره وارد شوید.', 'AUTH_REQUIRED');
    store.audit(ctx.user, 'BACKUP_UPLOADED', 'backup', name, { size }, ctx); store.save();
    completed = true;
    return { status: 201, body: { name, size } };
  } finally {
    if (handle) await handle.close().catch(() => {});
    await fs.promises.unlink(temp).catch(() => {});
    if (linked && !completed) await fs.promises.unlink(final).catch(() => {});
  }
});
route('GET', '/api/admin/backups/:name/download', ADMIN, async ctx => {
  const file = safeFile(ctx.params.name);
  store.audit(ctx.user, 'BACKUP_DOWNLOADED', 'backup', ctx.params.name, {}, ctx); store.save();
  return { headers: { 'Content-Type': 'application/octet-stream', 'Content-Disposition': `attachment; filename="${ctx.params.name}"` }, stream: res => new Promise((resolve, reject) => {
    const input = fs.createReadStream(file); input.on('error', reject); res.on('close', () => { input.destroy(); resolve(); }); input.on('end', resolve); input.pipe(res, { end: false });
  }) };
});
route('POST', '/api/admin/backups/:name/restore', ADMIN, async ctx => {
  if (ctx.body.confirm !== 'RESTORE') fail(400, 'تأیید بازیابی الزامی است.');
  if (!sec.verifyPassword(String(ctx.body.password || ''), ctx.user.passwordHash)) fail(403, 'رمز مدیر صحیح نیست.');
  const file = safeFile(ctx.params.name);
  const safety = create('before-restore');
  try { store.sql.restoreSnapshot(file); }
  catch (e) { fail(400, `بازیابی انجام نشد: ${e.message}. نسخهٔ پیش از بازیابی: ${safety}`); }
  // The database was committed: invalidate sessions even if reloading or audit fails.
  sec.destroyAllSessions();
  try { store.reloadFromSql(); }
  catch { fail(500, `داده‌ها بازیابی شدند، اما بارگذاری مجدد ناموفق بود. سرور را بررسی و بازراه‌اندازی کنید؛ نسخهٔ پیش از بازیابی: ${safety}`); }
  store.audit(null, 'BACKUP_RESTORED', 'backup', ctx.params.name, { by: ctx.user.username, safety }, ctx);
  store.save();
  return { body: { ok: true, safety, message: 'بازیابی انجام شد؛ با حساب و رمز موجود در نسخهٔ پشتیبان دوباره وارد شوید.' } };
});
