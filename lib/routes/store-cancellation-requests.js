'use strict';
const {atomicRoute:route,fail}=require('../http');
const store=require('../store'),validate=require('../validate');
const {createNotification,notifyStore}=require('../domain');
const owns=require('../store-access').owns;
route('POST','/api/store/orders/:id/cancellation-request',{roles:['store'],idempotent:true},ctx=>{
 const order=store.get().orders.find(o=>o.id===ctx.params.id);
 if(!order||order.orderType!=='STORE'||!owns(ctx.user,order))fail(404,'سفارش فروشگاه یافت نشد.');
 if(order.status==='STORE_PENDING_SALES')fail(409,'این سفارش پیش از تأیید فروش مستقیماً قابل لغو است.');
 if(order.status==='CANCELLED')fail(409,'این سفارش قبلاً لغو شده است.');
 const history=order.storeCancellationRequests||[];
 if(history.some(r=>r.status==='PENDING'))fail(409,'درخواست قبلی در انتظار بررسی فروش است.');
 const reason=validate.text(ctx.body.reason,{field:'دلیل درخواست',max:300,required:true}),now=store.nowIso();
 const request={id:store.uid(),status:'PENDING',reason,requestedAt:now,requestedBy:ctx.user.id,orderStatusAtRequest:order.status};
 order.storeCancellationRequests=[...history,request];order.updatedAt=now;
 store.audit(ctx.user,'STORE_CANCELLATION_REQUESTED','order',order.id,{requestId:request.id,reason,orderStatus:order.status},ctx);
 createNotification('sales','STORE_CANCELLATION_REQUESTED','order',order.id,`فروشگاه برای سفارش ${order.orderNo||'—'} درخواست لغو ثبت کرد؛ بررسی و تعیین تکلیف لازم است.`);
 store.save();return {body:{request}};
});
route('POST','/api/sales/store-cancellation-requests/:id/review',{roles:['sales'],idempotent:true},ctx=>{
 const order=store.get().orders.find(o=>o.id===ctx.params.id);
 if(!order||order.orderType!=='STORE')fail(404,'سفارش فروشگاه یافت نشد.');
 const history=order.storeCancellationRequests||[],request=history.find(r=>r.status==='PENDING');
 if(!request||ctx.body.requestId!==request.id)fail(409,'این درخواست دیگر در انتظار بررسی نیست.');
 const resolution=validate.text(ctx.body.resolution,{field:'نتیجه بررسی و اقدامات لازم',max:1000,required:true}),now=store.nowIso();
 order.storeCancellationRequests=history.map(r=>r.id===request.id?{...r,status:'REVIEWED',resolution,reviewedAt:now,reviewedBy:ctx.user.id}:r);order.updatedAt=now;
 store.audit(ctx.user,'STORE_CANCELLATION_REVIEWED','order',order.id,{requestId:request.id,resolution,orderStatus:order.status},ctx);
 notifyStore(order,'STORE_CANCELLATION_REVIEWED',`نتیجه بررسی درخواست لغو سفارش ${order.orderNo||'—'} ثبت شد؛ جزئیات سفارش را ببینید.`);
 store.save();return {body:{ok:true}};
});
